#!/usr/bin/python3

# Retourne la somme de deux nombres
def add(a, b):  # Définit la fonction 'add'
    """Retourne la somme de `a` et `b`.

    Args:
        a: Premier opérande (nombre).
        b: Deuxième opérande (nombre).

    Returns:
        La somme `a + b`.
    """
    return a + b  # Retourne le résultat
