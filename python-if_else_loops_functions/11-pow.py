#!/usr/bin/python3

# Retourne `a` élevé à la puissance `b`
def pow(a, b):  # Définit la fonction 'pow'
    """Calcule `a ** b`.

    Args:
        a: Base (nombre).
        b: Exposant (nombre).

    Returns:
        La valeur de `a` élevée à la puissance `b`.
    """
    return a ** b  # Retourne le résultat
