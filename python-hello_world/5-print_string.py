#!/usr/bin/python3

# Déclare la variable `str` contenant le nom de l'école
str = "Holberton School"  # Affecte une valeur à 'str'

# Imprime la chaîne répétée 3 fois (concaténation via multiplication de chaîne)
print(f"{str * 3}")  # Affiche à l'écran

# Imprime les neuf premiers caractères de la chaîne (slice)
print(str[:9])  # Affiche à l'écran
