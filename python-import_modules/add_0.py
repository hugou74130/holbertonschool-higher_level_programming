#!/usr/bin/python3

# Fonction d'addition simple
def add(a, b):  # Définit la fonction 'add'
    """Retourne la somme de deux entiers `a` et `b`.

    Args:
        a: premier opérande (int ou nombre).
        b: second opérande (int ou nombre).

    Returns:
        La somme `a + b`.
    """
    # Retourne la somme des deux paramètres sans modifier leur type
    return (a + b)  # Retourne le résultat
