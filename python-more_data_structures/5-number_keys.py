#!/usr/bin/python3

# Retourne le nombre de clés d'un dictionnaire
def number_keys(a_dictionary):  # Définit la fonction 'number_keys'
    """Retourne le nombre d'entrées (clés) présentes dans `a_dictionary`.

    Args:
        a_dictionary (dict): le dictionnaire à inspecter.

    Returns:
        int: nombre de clés.
    """
    # len() appliqué au dictionnaire renvoie le nombre de clés
    return len(a_dictionary)  # Retourne le résultat
